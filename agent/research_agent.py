"""LLM Research Agent for automated strategy research.

Applies RAG-style architecture (Retrieve → Reason → Generate) to financial
research workflows:
- Extract signals from research reports, announcements, earnings calls
- Generate factor hypotheses from market narratives
- Summarize portfolio risk/return attribution in natural language
- Cross-reference news with factor data for alpha discovery

Architecture:
    Text Input → Chunking → Embedding/Keyword Extraction → Signal Extraction
         ↓                                                    ↓
    Factor Data ← Context Assembly ← Relevant Chunk Retrieval
         ↓
    LLM Reasoning → Structured Output (sentiment / hypothesis / summary)

This module demonstrates how Agent/RAG skills transfer directly to quant.

Backend honesty:
- ``mode="llm"`` without an API key is *visibly* downgraded: ``mode`` /
  ``effective_mode`` become "keyword", while ``requested_mode`` stays "llm",
  ``mode_downgraded`` is True and ``backend`` is "keyword". A warning is
  logged. ``status()`` returns the whole picture.
- Every LLM call path records ``last_fallback_reason`` when it degrades to the
  keyword implementation, so a caller can tell LLM output from keyword output.
- LLM responses may be bare JSON arrays, dict wrappers such as
  ``{"signals": [...]}`` / ``{"hypotheses": [...]}``, fenced ```json blocks,
  or prose around the JSON; all are parsed. Field values are validated
  against the ``ExtractedSignal`` / ``FactorHypothesis`` contracts: entries
  missing required fields are dropped, out-of-range values are repaired, and
  every drop/repair is warned about.

Usage:
    agent = ResearchAgent(api_key="sk-...")
    signals = agent.extract_signals_from_text(research_report, stock="600519")
    summary = agent.summarize_attribution(factor_contributions, daily_returns)
    hypotheses = agent.generate_hypotheses(market_narrative, factor_data)
"""

from __future__ import annotations

import hashlib
import json
import math
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

import numpy as np
import pandas as pd

from quant_platform.utils.logging import get_logger

logger = get_logger(__name__)


@dataclass
class ExtractedSignal:
    """A structured signal extracted from text."""
    stock: str
    signal_type: Literal["sentiment", "event", "hypothesis", "risk"]
    direction: Literal["bullish", "bearish", "neutral"]
    strength: float  # -1 to 1
    confidence: float  # 0 to 1
    reasoning: str
    source_text: str
    factor_implications: dict[str, float] = field(default_factory=dict)


@dataclass
class FactorHypothesis:
    """A factor hypothesis generated by the LLM."""
    factor_name: str
    description: str
    expected_ic: float
    economic_logic: str
    data_requirements: list[str]
    risk_factors: list[str]
    confidence: float


class ResearchAgent:
    """LLM-powered research agent for quantitative strategy research.

    Uses RAG-pattern: retrieve context → reason with LLM → structured output.

    Modes:
    - keyword: Zero-cost keyword extraction (default, for demo)
    - llm: Real DeepSeek/LLM API calls (requires DEEPSEEK_API_KEY). If the key
      is missing the agent runs in keyword mode but keeps
      ``requested_mode="llm"``, ``mode_downgraded=True`` and
      ``backend="keyword"`` so the downgrade is never silent.

    Examples:
        # Analyze a research report
        agent = ResearchAgent()
        signals = agent.extract_signals_from_text(
            "茅台Q3净利润同比增长30%，超出市场预期...",
            stock="600519"
        )

        # Generate factor hypotheses from market narrative
        hypotheses = agent.generate_hypotheses(
            "近期新能源板块资金持续流入，光伏装机量超预期...",
            available_factors=["momentum", "volatility", "turnover"]
        )

        # Summarize portfolio attribution in natural language
        summary = agent.summarize_attribution(
            {"momentum": 0.003, "value": -0.001, "size": 0.002},
            daily_returns
        )
    """

    #: Hard caps on LLM input assembled from user data. They keep a broken or
    #: hostile caller from pushing unbounded text into a paid API request.
    MAX_NARRATIVE_CHARS = 2000
    MAX_CONTEXT_CHARS = 500
    MAX_AVAILABLE_FACTORS = 50
    MAX_FACTOR_NAME_CHARS = 100
    MAX_CONTRIBUTIONS = 50
    MAX_LIST_ITEMS = 20
    MAX_REASONING_CHARS = 1000
    MAX_STOCK_CHARS = 100
    MAX_SOURCE_TYPE_CHARS = 50
    MAX_PERIOD_CHARS = 100
    #: Each chunk fits in the prompt excerpt exactly (no silent tail loss),
    #: and a pathological document cannot trigger thousands of paid calls.
    MAX_CHUNK_CHARS = 1500
    MAX_CHUNKS = 50
    #: Final defense: no prompt may exceed this many characters.
    MAX_PROMPT_CHARS = 20_000
    MAX_PROMPT_CACHE_ENTRIES = 256

    _SIGNAL_TYPES = frozenset({"sentiment", "event", "hypothesis", "risk"})
    _DIRECTION_ALIASES = {
        "bullish": "bullish",
        "bearish": "bearish",
        "neutral": "neutral",
        "up": "bullish",
        "down": "bearish",
        "bull": "bullish",
        "bear": "bearish",
        "positive": "bullish",
        "negative": "bearish",
        "看多": "bullish",
        "看空": "bearish",
        "利好": "bullish",
        "利空": "bearish",
        "中性": "neutral",
    }
    _SIGNAL_WRAPPER_KEYS = ("signals", "items", "results", "data", "output")
    _HYPOTHESIS_WRAPPER_KEYS = ("hypotheses", "items", "results", "data", "output")
    _SIGNAL_MARKERS = ("signal_type", "direction", "strength")
    _HYPOTHESIS_MARKERS = ("factor_name", "expected_ic", "economic_logic")
    _FENCED_JSON_RE = re.compile(
        r"```[ \t]*(?:json)?[ \t]*\r?\n?(?P<body>.*?)```",
        re.IGNORECASE | re.DOTALL,
    )

    def __init__(
        self,
        api_key: str | None = None,
        model: str = "deepseek-chat",
        mode: Literal["keyword", "llm"] = "keyword",
        cache_dir: str | None = None,
    ):
        if mode not in ("keyword", "llm"):
            raise ValueError(f"mode must be 'keyword' or 'llm', got {mode!r}")

        self.api_key = api_key or os.environ.get("DEEPSEEK_API_KEY")
        self.model = model
        self.requested_mode = mode

        # Explicit, observable downgrade instead of a silent one: mode stays
        # truthful about what runs; requested_mode/mode_downgraded preserve
        # the fact that the caller asked for the LLM.
        downgraded = mode == "llm" and not self.api_key
        self.downgrade_reason: str | None = None
        if downgraded:
            self.downgrade_reason = (
                "mode='llm' requested but DEEPSEEK_API_KEY (or api_key) is not "
                "set; running keyword mode, no LLM calls will be made"
            )
            logger.warning("ResearchAgent downgraded: %s", self.downgrade_reason)
        self.mode = "keyword" if downgraded else mode

        self.cache_dir = Path(cache_dir) if cache_dir else Path("./.agent_cache")
        self.cache_dir.mkdir(exist_ok=True)
        self._client = None
        self._cache: dict[str, Any] = {}

        #: Set whenever an LLM call path falls back to keyword extraction so
        #: callers can distinguish LLM output from keyword output. Aggregates
        #: over all chunks of one public call (first reason first).
        self.last_fallback_reason: str | None = None
        #: True when a long input was truncated to MAX_CHUNKS before analysis.
        self.last_input_truncated: bool = False

    # ──────────────────────────────────────────────────────────────
    # Backend status
    # ──────────────────────────────────────────────────────────────

    @property
    def effective_mode(self) -> str:
        """Backend that actually runs ("keyword" or "llm")."""
        return self.mode

    @property
    def mode_downgraded(self) -> bool:
        """True when mode='llm' was requested but keyword mode actually runs.

        Derived from live state, so it stays truthful if ``mode`` is changed.
        """
        return self.requested_mode == "llm" and self.mode == "keyword"

    @property
    def is_llm(self) -> bool:
        return self.mode == "llm"

    @property
    def backend(self) -> str:
        """Machine-readable backend label for result provenance."""
        return f"llm:{self.model}" if self.mode == "llm" else "keyword"

    def status(self) -> dict[str, Any]:
        """Return the requested vs. effective backend state.

        Callers should surface this next to any result produced by the agent
        so a downgraded (keyword) run is never mistaken for LLM output.
        """
        return {
            "requested_mode": self.requested_mode,
            "effective_mode": self.effective_mode,
            "backend": self.backend,
            "mode_downgraded": self.mode_downgraded,
            "downgrade_reason": self.downgrade_reason if self.mode_downgraded else None,
            "last_fallback_reason": self.last_fallback_reason,
            "input_truncated": self.last_input_truncated,
        }

    def _reset_fallback_state(self) -> None:
        """Clear per-call degradation flags before a public operation."""
        self.last_fallback_reason = None
        self.last_input_truncated = False

    def _record_fallback(self, reason: str) -> None:
        """Record an LLM->keyword degradation, keeping earlier chunk reasons."""
        if self.last_fallback_reason is None:
            self.last_fallback_reason = reason
        else:
            self.last_fallback_reason = f"{self.last_fallback_reason}; {reason}"

    # ──────────────────────────────────────────────────────────────
    # Core: Extract signals from research text
    # ──────────────────────────────────────────────────────────────

    def extract_signals_from_text(
        self,
        text: str,
        stock: str = "",
        source_type: str = "research_report",
    ) -> list[ExtractedSignal]:
        """Extract structured trading signals from unstructured financial text.

        Args:
            text: Research report, news article, or announcement text
            stock: Stock code if known
            source_type: Type of source (research_report, announcement, news)

        Returns:
            List of ExtractedSignal objects
        """
        self._reset_fallback_state()
        # Chunks are sized to the prompt excerpt; an extreme document is
        # truncated to MAX_CHUNKS so total LLM calls stay bounded.
        chunks = self._chunk_text(text, max_chars=self.MAX_CHUNK_CHARS)
        # The cap exists to bound paid LLM calls; keyword mode is local, so
        # it processes every chunk.
        if self.mode == "llm" and len(chunks) > self.MAX_CHUNKS:
            logger.warning(
                "ResearchAgent: input has %d chunks, analyzing only the first "
                "%d (last_input_truncated=True)", len(chunks), self.MAX_CHUNKS,
            )
            self.last_input_truncated = True
            chunks = chunks[: self.MAX_CHUNKS]
        all_signals = []

        for chunk in chunks:
            if self.mode == "llm":
                signals = self._extract_signals_llm(chunk, stock, source_type)
            else:
                signals = self._extract_signals_keyword(chunk, stock)
            all_signals.extend(signals)

        # Deduplicate
        return self._deduplicate_signals(all_signals)

    def _extract_signals_keyword(self, text: str, stock: str) -> list[ExtractedSignal]:
        """Keyword-based signal extraction (zero cost, deterministic)."""
        signals = []

        # Financial metric extraction patterns
        patterns = {
            "revenue_growth": (r"营[业收].*?增[长速][\s:：]*(\d+\.?\d*)%", "bullish"),
            "profit_growth": (r"净利[润润].*?增[长速][\s:：]*(\d+\.?\d*)%", "bullish"),
            "profit_decline": (r"净利[润润].*?[下下]降[\s:：]*(\d+\.?\d*)%", "bearish"),
            "pe_ratio": (r"[市PE][E盈].*?(\d+\.?\d*)倍", None),
            "target_price": (r"目标价[\s:：]*(\d+\.?\d*)元", None),
            "buyback": (r"回购.*?(\d+\.?\d*)[亿万]", "bullish"),
            "dividend_yield": (r"[股分][息红].*?(\d+\.?\d*)%", "bullish"),
        }

        for metric_name, (pattern, default_dir) in patterns.items():
            match = re.search(pattern, text)
            if match:
                value = float(match.group(1))
                if default_dir:
                    direction = default_dir
                    strength = min(1.0, value / 100) if value > 0 else 0.3
                else:
                    direction = "neutral"
                    strength = 0.0

                signals.append(ExtractedSignal(
                    stock=stock,
                    signal_type="event",
                    direction=direction,
                    strength=strength if direction == "bullish" else -strength,
                    confidence=0.6,
                    reasoning=f"Extracted {metric_name}={value} from text",
                    source_text=text[:200],
                    factor_implications=self._infer_factor_implications(metric_name, value),
                ))

        # Sentiment keywords
        sentiment_score = self._keyword_sentiment(text)
        if abs(sentiment_score) > 0.2:
            signals.append(ExtractedSignal(
                stock=stock,
                signal_type="sentiment",
                direction="bullish" if sentiment_score > 0 else "bearish",
                strength=abs(sentiment_score),
                confidence=0.5,
                reasoning=f"Keyword sentiment score: {sentiment_score:.2f}",
                source_text=text[:200],
            ))

        return signals

    def _extract_signals_llm(
        self, text: str, stock: str, source_type: str
    ) -> list[ExtractedSignal]:
        """LLM-based signal extraction (higher quality, costs money)."""
        stock_text = self._bounded_text(stock, self.MAX_STOCK_CHARS)
        source_text = self._bounded_text(source_type, self.MAX_SOURCE_TYPE_CHARS)
        text_excerpt = self._bounded_text(text, self.MAX_CHUNK_CHARS)
        prompt = f"""Analyze this Chinese financial text and extract trading signals.

Text ({source_text}):
{text_excerpt}

Stock: {stock_text}

Output a JSON array of signals. Each signal has:
- signal_type: "sentiment" | "event" | "hypothesis" | "risk"
- direction: "bullish" | "bearish" | "neutral"
- strength: float -1.0 to 1.0
- confidence: float 0.0 to 1.0
- reasoning: brief explanation in Chinese
- factor_implications: dict of factor_name -> expected_impact (-1 to 1)

Output ONLY valid JSON array, no other text."""

        try:
            result = self._call_llm(prompt)
            items = self._parse_llm_json(
                result,
                wrapper_keys=self._SIGNAL_WRAPPER_KEYS,
                item_markers=self._SIGNAL_MARKERS,
            )
            return self._signals_from_items(items, stock, text)
        except Exception as e:
            self._record_fallback(f"llm_signal_extraction: {e}")
            logger.warning("LLM signal extraction failed: %s, falling back to keyword", e)
            return self._extract_signals_keyword(text, stock)

    # ──────────────────────────────────────────────────────────────
    # Generate factor hypotheses from market narratives
    # ──────────────────────────────────────────────────────────────

    def generate_hypotheses(
        self,
        narrative: str,
        available_factors: list[str] | None = None,
        market_context: str = "",
    ) -> list[FactorHypothesis]:
        """Generate testable factor hypotheses from a market narrative.

        Args:
            narrative: Market narrative or thesis (e.g., "新能源板块资金持续流入")
            available_factors: Existing factors to check against
            market_context: Additional market context

        Returns:
            List of FactorHypothesis objects
        """
        self._reset_fallback_state()
        if self.mode == "llm":
            return self._generate_hypotheses_llm(narrative, available_factors, market_context)
        return self._generate_hypotheses_keyword(narrative, available_factors)

    def _generate_hypotheses_keyword(
        self, narrative: str, available_factors: list[str] | None
    ) -> list[FactorHypothesis]:
        """Keyword-based hypothesis generation."""
        hypotheses = []

        # Map narrative themes to factor hypotheses
        theme_map = {
            "资金流入": ("turnover_20d", "资金流入驱动换手率上升，短期动量效应增强", 0.04),
            "业绩": ("roe", "业绩增长反映在ROE改善上，质量因子应有正IC", 0.035),
            "估值": ("pb_ratio", "估值修复推动低PB股票跑赢，价值因子有效", 0.03),
            "波动": ("volatility_60d", "市场波动加大，低波动异象更显著", 0.04),
            "动量": ("momentum_12m", "趋势延续，中期动量效应增强", 0.045),
            "规模": ("log_market_cap", "小盘股流动性改善，规模效应显现", 0.03),
            "政策": ("momentum_1m", "政策催化短期行情，1月动量效应增强", 0.035),
            "行业": ("amplitude_20d", "行业轮动加速，振幅因子能捕捉波动", 0.025),
        }

        for theme, (factor, logic, ic) in theme_map.items():
            if theme in narrative:
                if available_factors is None or factor in available_factors:
                    hypotheses.append(FactorHypothesis(
                        factor_name=factor,
                        description=f"{theme}主题下{factor}因子应有正向预测力",
                        expected_ic=ic,
                        economic_logic=logic,
                        data_requirements=["日频行情数据", "财务数据"],
                        risk_factors=["主题持续性不确定", "可能已被市场定价"],
                        confidence=0.5,
                    ))

        return hypotheses

    def _generate_hypotheses_llm(
        self, narrative: str, available_factors: list[str] | None, market_context: str
    ) -> list[FactorHypothesis]:
        """LLM-based hypothesis generation."""
        factors_text = (
            ", ".join(
                self._bounded_text(f, self.MAX_FACTOR_NAME_CHARS)
                for f in available_factors[: self.MAX_AVAILABLE_FACTORS]
            )[: self.MAX_NARRATIVE_CHARS]
            if available_factors else "any"
        )
        narrative_text = self._bounded_text(narrative, self.MAX_NARRATIVE_CHARS)
        context_text = self._bounded_text(market_context, self.MAX_CONTEXT_CHARS)
        prompt = f"""You are a quantitative researcher. Based on this market narrative, generate factor hypotheses.

Narrative: {narrative_text}
Available factors: {factors_text}
Market context: {context_text}

Generate 2-4 testable hypotheses as a JSON array. Each:
- factor_name: which factor to test
- description: one-line description
- expected_ic: expected IC magnitude (e.g., 0.03-0.06)
- economic_logic: why this should work (in Chinese)
- data_requirements: what data is needed
- risk_factors: what could go wrong
- confidence: 0-1

Output ONLY valid JSON array."""

        try:
            result = self._call_llm(prompt)
            items = self._parse_llm_json(
                result,
                wrapper_keys=self._HYPOTHESIS_WRAPPER_KEYS,
                item_markers=self._HYPOTHESIS_MARKERS,
            )
            return self._hypotheses_from_items(items, available_factors)
        except Exception as e:
            self._record_fallback(f"llm_hypothesis_generation: {e}")
            logger.warning("LLM hypothesis generation failed: %s", e)
            return self._generate_hypotheses_keyword(narrative, available_factors)

    # ──────────────────────────────────────────────────────────────
    # Summarize attribution in natural language
    # ──────────────────────────────────────────────────────────────

    def summarize_attribution(
        self,
        factor_contributions: dict[str, float],
        daily_returns: pd.Series | None = None,
        period: str = "本月",
    ) -> str:
        """Generate a natural language summary of portfolio attribution.

        Args:
            factor_contributions: factor_name -> contribution (decimal)
            daily_returns: daily return series for context
            period: time period description

        Returns:
            Chinese natural language summary
        """
        self._reset_fallback_state()
        if self.mode == "llm":
            return self._summarize_attribution_llm(factor_contributions, daily_returns, period)
        return self._summarize_attribution_keyword(factor_contributions, daily_returns, period)

    def _summarize_attribution_keyword(
        self,
        contributions: dict[str, float],
        daily_returns: pd.Series | None,
        period: str,
    ) -> str:
        """Keyword-based attribution summary."""
        lines = [f"【{period}组合归因分析】"]

        # Sort by absolute contribution
        sorted_factors = sorted(contributions.items(), key=lambda x: abs(x[1]), reverse=True)

        # Top positive contributors
        positives = [(k, v) for k, v in sorted_factors if v > 0]
        negatives = [(k, v) for k, v in sorted_factors if v < 0]

        if positives:
            lines.append("正贡献因子：" + "、".join(
                f"{k}(+{v*10000:.0f}bps)" for k, v in positives[:3]
            ))

        if negatives:
            lines.append("负贡献因子：" + "、".join(
                f"{k}({v*10000:.0f}bps)" for k, v in negatives[:3]
            ))

        # Performance context
        if daily_returns is not None and len(daily_returns) > 0:
            total_ret = (1 + daily_returns).prod() - 1
            vol = daily_returns.std() * np.sqrt(252)
            sharpe = (daily_returns.mean() * 252) / vol if vol > 0 else 0
            lines.append(f"期间收益：{total_ret:.2%}，年化波动：{vol:.2%}，夏普：{sharpe:.2f}")

        # Factor insight
        best_factor = sorted_factors[0] if sorted_factors else None
        if best_factor:
            lines.append(f"核心驱动因子：{best_factor[0]}，贡献{best_factor[1]*10000:.0f}bps")

        return "\n".join(lines)

    def _summarize_attribution_llm(
        self,
        contributions: dict[str, float],
        daily_returns: pd.Series | None,
        period: str,
    ) -> str:
        """LLM-based attribution summary."""
        context = ""
        if daily_returns is not None and len(daily_returns) > 0:
            total_ret = (1 + daily_returns).prod() - 1
            vol = daily_returns.std() * np.sqrt(252)
            context = f"期间收益：{total_ret:.2%}，年化波动率：{vol:.2%}"

        # Bound the factor list and name lengths and drop non-finite values so
        # a huge or corrupted attribution dict cannot blow up the prompt.
        finite = [
            (str(k), float(v))
            for k, v in contributions.items()
            if self._coerce_float(v) is not None
        ]
        finite.sort(key=lambda kv: abs(kv[1]), reverse=True)
        top = finite[: self.MAX_CONTRIBUTIONS]
        contributions_text = json.dumps(
            {
                self._prompt_key(k, self.MAX_FACTOR_NAME_CHARS): round(v * 10000, 1)
                for k, v in top
            },
            ensure_ascii=False,
        )
        period_text = self._bounded_text(period, self.MAX_PERIOD_CHARS)

        prompt = f"""用中文写一段简洁的组合归因分析（100字以内）。

{period_text}因子贡献（bps）：
{contributions_text}

{context}

要求：指出主要正/负贡献因子，分析原因，给出建议。"""

        try:
            result = self._call_llm(prompt)
            if not isinstance(result, str) or not result.strip():
                raise ValueError("empty LLM attribution response")
            return result
        except Exception as e:
            self._record_fallback(f"llm_attribution_summary: {e}")
            logger.warning("LLM attribution summary failed: %s, falling back to keyword", e)
            return self._summarize_attribution_keyword(contributions, daily_returns, period)

    # ──────────────────────────────────────────────────────────────
    # Risk narrative generation
    # ──────────────────────────────────────────────────────────────

    def describe_risk(
        self,
        risk_decomposition: dict[str, Any],
        regime: str = "neutral",
    ) -> str:
        """Generate a natural language risk report.

        Args:
            risk_decomposition: dict with total_risk, factor_risk, specific_risk, etc.
            regime: market regime (risk_on, neutral, cautious, risk_off)

        Returns:
            Chinese risk report
        """
        total = risk_decomposition.get("total_risk", 0)
        factor = risk_decomposition.get("factor_risk", 0)
        specific = risk_decomposition.get("specific_risk", 0)
        r_sq = risk_decomposition.get("r_squared", 0)

        regime_desc = {
            "risk_on": "市场风险偏好较高",
            "neutral": "市场状态中性",
            "cautious": "市场趋于谨慎",
            "risk_off": "市场避险情绪升温",
        }

        lines = ["【风险概况】"]
        lines.append(f"总风险：{total:.1%}（年化），其中因子风险{factor:.1%}，特异性风险{specific:.1%}")
        lines.append(f"模型解释度R²={r_sq:.1%}，{regime_desc.get(regime, '')}")

        # Factor exposures
        exposures = risk_decomposition.get("factor_exposures", {})
        if exposures:
            top_exposure = max(exposures.items(), key=lambda x: abs(x[1]))
            lines.append(f"最大因子暴露：{top_exposure[0]}（{top_exposure[1]:.3f}）")

        # Factor contributions
        contributions = risk_decomposition.get("factor_contributions", {})
        if contributions:
            top_contrib = max(contributions.items(), key=lambda x: abs(x[1]))
            lines.append(f"风险贡献最大因子：{top_contrib[0]}（{top_contrib[1]*10000:.0f}bps）")

        return "\n".join(lines)

